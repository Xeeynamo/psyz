// DPCT: depth cue triple using RGB0<<16 as input (front of color FIFO).
static void DPCT(unsigned int cmd) {
    int sf = (cmd >> 19) & 1, lm = (cmd >> 10) & 1;
    FLAG = 0;
    for (int i = 0; i < 3; i++) {
        int r = RGB0 & 0xFF;
        int g = (RGB0 >> 8) & 0xFF;
        int b = (RGB0 >> 16) & 0xFF;
        depth_cue(sf, lm, r << 16, g << 16, b << 16);
        color_fifo_push();
    }
    FLAG_update_error();
}

