void Psyz_GteCtrlWrite(unsigned idx, unsigned int v) {
    switch (idx) {
    case 0:
        M.m[0][0] = (short)(v & 0xFFFF);
        M.m[0][1] = (short)((v >> 16) & 0xFFFF);
        break;
    case 1:
        M.m[0][2] = (short)(v & 0xFFFF);
        M.m[1][0] = (short)((v >> 16) & 0xFFFF);
        break;
    case 2:
        M.m[1][1] = (short)(v & 0xFFFF);
        M.m[1][2] = (short)((v >> 16) & 0xFFFF);
        break;
    case 3:
        M.m[2][0] = (short)(v & 0xFFFF);
        M.m[2][1] = (short)((v >> 16) & 0xFFFF);
        break;
    case 4:
        M.m[2][2] = (short)(v & 0xFFFF);
        break;
    case 5:
        M.t[0] = (int)v;
        break;
    case 6:
        M.t[1] = (int)v;
        break;
    case 7:
        M.t[2] = (int)v;
        break;
    case 8:
        L1.m[0][0] = (short)(v & 0xFFFF);
        L1.m[0][1] = (short)((v >> 16) & 0xFFFF);
        break;
    case 9:
        L1.m[0][2] = (short)(v & 0xFFFF);
        L1.m[1][0] = (short)((v >> 16) & 0xFFFF);
        break;
    case 10:
        L1.m[1][1] = (short)(v & 0xFFFF);
        L1.m[1][2] = (short)((v >> 16) & 0xFFFF);
        break;
    case 11:
        L1.m[2][0] = (short)(v & 0xFFFF);
        L1.m[2][1] = (short)((v >> 16) & 0xFFFF);
        break;
    case 12:
        L1.m[2][2] = (short)(v & 0xFFFF);
        break;
    case 13:
        L1.t[0] = (int)v;
        break;
    case 14:
        L1.t[1] = (int)v;
        break;
    case 15:
        L1.t[2] = (int)v;
        break;
    case 16:
        L2.m[0][0] = (short)(v & 0xFFFF);
        L2.m[0][1] = (short)((v >> 16) & 0xFFFF);
        break;
    case 17:
        L2.m[0][2] = (short)(v & 0xFFFF);
        L2.m[1][0] = (short)((v >> 16) & 0xFFFF);
        break;
    case 18:
        L2.m[1][1] = (short)(v & 0xFFFF);
        L2.m[1][2] = (short)((v >> 16) & 0xFFFF);
        break;
    case 19:
        L2.m[2][0] = (short)(v & 0xFFFF);
        L2.m[2][1] = (short)((v >> 16) & 0xFFFF);
        break;
    case 20:
        L2.m[2][2] = (short)(v & 0xFFFF);
        break;
    case 21:
        L2.t[0] = (int)v;
        break;
    case 22:
        L2.t[1] = (int)v;
        break;
    case 23:
        L2.t[2] = (int)v;
        break;
    // OFX/OFY are 20.12 fixed-point on the real GTE (PSY-Q's SetGeomOffset
    // writes `pixels << 16` into the ctrl reg). Psy-Z's RTPS math stores
    // them as integer pixels (it later does `OFX << 16` to align to 16.16),
    // so convert on the way in. Use arithmetic shift to keep sign.
    case 24:
        OFX = (int)v >> 16;
        break;
    case 25:
        OFY = (int)v >> 16;
        break;
    case 26:
        H = (u16)(v & 0xFFFF);
        break;
    case 27:
        DQA = (short)(v & 0xFFFF);
        break;
    case 28:
        DQB = (int)v;
        break;
    case 29:
        ZSF3 = (short)(v & 0xFFFF);
        break;
    case 30:
        ZSF4 = (short)(v & 0xFFFF);
        break;
    case 31:
        FLAG = v;
        break;
    default:
        break;
    }
}

void Psyz_GteCommand(unsigned int cmd) {
    // bits 0..5 select the op
    unsigned op = cmd & 0x3F;
    switch (op) {
    case 0x01:
        RTPS(cmd);
        break;
    case 0x06:
        NCLIP();
        break;
    case 0x0C:
        OP(cmd);
        break;
    case 0x10:
        DPCS(cmd);
        break;
    case 0x11:
        INTPL(cmd);
        break;
    case 0x12:
        MVMVA(cmd);
        break;
    case 0x13:
        NCDS(cmd);
        break;
    case 0x14:
        CDP(cmd);
        break;
    case 0x16:
        NCDT(cmd);
        break;
    case 0x1B:
        NCCS(cmd);
        break;
    case 0x1C:
        CC(cmd);
        break;
    case 0x1E:
        NCS(cmd);
        break;
    case 0x20:
        NCT(cmd);
        break;
    case 0x28:
        SQR(cmd);
        break;
    case 0x29:
        DCPL(cmd);
        break;
    case 0x2A:
        DPCT(cmd);
        break;
    case 0x2D:
        AVSZ3();
        break;
    case 0x2E:
        AVSZ4();
        break;
    case 0x30:
        RTPT(cmd);
        break;
    case 0x3D:
        GPF(cmd);
        break;
    case 0x3E:
        GPL(cmd);
        break;
    case 0x3F:
        NCCT(cmd);
        break;
    default:
        WARNF("unhandled GTE op:%02X", op);
        break;
    }
}
