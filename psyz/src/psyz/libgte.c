int rsin(int a) {
    if (a < 0) {
        return -(int)rcossin_tbl[-a & 0xFFF][0];
    }
    return (int)rcossin_tbl[a & 0xFFF][0];
}

int rcos(int a) {
    if (a < 0) {
        a = -a;
    }
    return (int)rcossin_tbl[a & 0xFFF][1];
}

static void rcossin(int a, int* c, int* s) {
    if (a < 0) {
        a = -a;
        *c = (int)rcossin_tbl[a & 0xFFF][1];
        *s = -(int)rcossin_tbl[a & 0xFFF][0];
    } else {
        *c = (int)rcossin_tbl[a & 0xFFF][1];
        *s = (int)rcossin_tbl[a & 0xFFF][0];
    }
}

MATRIX* RotMatrix(SVECTOR* r, MATRIX* m) {
    int sx, cx, sy, nsy, cy, sz, cz;
    int t;

    rcossin(r->vx, &cx, &sx);
    rcossin(r->vy, &cy, &sy);
    nsy = -sy;

    m->m[0][2] = sy;
    m->m[1][2] = -(cy * sx) >> 12;
    m->m[2][2] = (cy * cx) >> 12;

    rcossin(r->vz, &cz, &sz);

    m->m[0][0] = (cz * cy) >> 12;
    m->m[0][1] = -(sz * cy) >> 12;

    t = (cz * nsy) >> 12;
    m->m[1][0] = ((sz * cx) >> 12) - ((t * sx) >> 12);
    m->m[2][0] = ((sz * sx) >> 12) + ((t * cx) >> 12);

    t = (sz * nsy) >> 12;
    m->m[1][1] = ((cz * cx) >> 12) + ((t * sx) >> 12);
    m->m[2][1] = ((cz * sx) >> 12) - ((t * cx) >> 12);

    return m;
}

MATRIX* RotMatrixY(long r, MATRIX* m) {
    int c, s;
    int a0 = m->m[0][0], a1 = m->m[0][1], a2 = m->m[0][2];
    int b0 = m->m[2][0], b1 = m->m[2][1], b2 = m->m[2][2];

    rcossin((short)r, &c, &s);
    m->m[0][0] = (short)((c * a0 + s * b0) >> 12);
    m->m[0][1] = (short)((c * a1 + s * b1) >> 12);
    m->m[0][2] = (short)((c * a2 + s * b2) >> 12);
    m->m[2][0] = (short)((c * b0 - s * a0) >> 12);
    m->m[2][1] = (short)((c * b1 - s * a1) >> 12);
    m->m[2][2] = (short)((c * b2 - s * a2) >> 12);
    return m;
}

