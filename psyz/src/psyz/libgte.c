MATRIX* RotMatrixYXZ(SVECTOR* r, MATRIX* m) {
    int sx, cx, sy, cy, sz, cz;
    int sysx, cysx;

    rcossin(r->vx, &cx, &sx);
    rcossin(r->vy, &cy, &sy);
    rcossin(r->vz, &cz, &sz);

    sysx = (sy * sx) >> 12;
    cysx = (cy * sx) >> 12;

    m->m[0][0] = ((cy * cz) >> 12) + ((sysx * sz) >> 12);
    m->m[0][1] = ((sysx * cz) >> 12) - ((cy * sz) >> 12);
    m->m[0][2] = (sy * cx) >> 12;
    m->m[1][0] = (cx * sz) >> 12;
    m->m[1][1] = (cx * cz) >> 12;
    m->m[1][2] = -sx;
    m->m[2][0] = ((cysx * sz) >> 12) - ((sy * cz) >> 12);
    m->m[2][1] = ((sy * sz) >> 12) + ((cysx * cz) >> 12);
    m->m[2][2] = (cy * cx) >> 12;

    m->t[0] = 0;
    m->t[1] = 0;
    m->t[2] = 0;
    return m;
}

