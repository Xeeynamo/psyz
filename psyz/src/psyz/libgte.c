#define FLAG_MAC2_OVF_NEG (1u << 26)
#define FLAG_MAC3_OVF_NEG (1u << 25)
#define FLAG_IR1_SAT (1u << 24)
#define FLAG_IR2_SAT (1u << 23)
#define FLAG_IR3_SAT (1u << 22)
#define FLAG_COL_R_SAT (1u << 21) // RGB FIFO R saturated to 0..ff
